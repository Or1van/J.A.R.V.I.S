_order: list[int] = []
_shown: list[int] = []  # ідеї, які щойно прозвучали (для "запиши другу ідею")


def _next_three() -> str:
    global _shown
    if not _order:
        _order.extend(random.sample(range(len(IDEAS)), len(IDEAS)))
    _shown = [_order.pop() for _ in range(min(3, len(_order)))]
    names = ("Перша", "Друга", "Третя")
    text = " ".join(f"{names[i]}: {IDEAS[idx][0]} — {IDEAS[idx][1]}" for i, idx in enumerate(_shown))
    runtime.more = _next_three
    return text + " Скажіть «ще» або «запиши другу ідею»."


@tool
def suggest_ideas() -> str:
    """Запропонувати три ідеї для нового проєкту (програмування, боти, ігри, навички Джарвіса)."""
    return _next_three()


